"use strict";

const ERROR_CODES = Object.freeze({
  ABORTED: "ABORTED",
  AGENT_BUSY: "AGENT_BUSY",
  AGENT_NOT_FOUND: "AGENT_NOT_FOUND",
  TARGET_AGENT_UNAVAILABLE: "TARGET_AGENT_UNAVAILABLE",
  CAPABILITY_UNSUPPORTED: "CAPABILITY_UNSUPPORTED",
  TARGET_NOT_FOUND: "TARGET_NOT_FOUND",
  IDEMPOTENCY_CONFLICT: "IDEMPOTENCY_CONFLICT",
  INVALID_ARGUMENT: "INVALID_ARGUMENT",
  UNAUTHORIZED: "UNAUTHORIZED",
  FORBIDDEN: "FORBIDDEN",
  NOT_FOUND: "NOT_FOUND",
  RATE_LIMITED: "RATE_LIMITED",
  UPSTREAM_TIMEOUT: "UPSTREAM_TIMEOUT",
  UPSTREAM_UNAVAILABLE: "UPSTREAM_UNAVAILABLE",
  INTERNAL_ERROR: "INTERNAL_ERROR",
});

function normalizeRunErrorCode(code) {
  if (code === ERROR_CODES.RATE_LIMITED) return ERROR_CODES.AGENT_BUSY;
  return code || ERROR_CODES.INTERNAL_ERROR;
}

module.exports = { ERROR_CODES, normalizeRunErrorCode };
